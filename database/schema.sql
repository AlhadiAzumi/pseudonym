-- Skema PostgreSQL untuk Supabase.
-- Jalankan seluruh file ini di Supabase Dashboard > SQL Editor > New query.

CREATE TABLE IF NOT EXISTS users (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username     VARCHAR(30) UNIQUE,
  email        VARCHAR(190) NOT NULL UNIQUE,
  google_id    VARCHAR(64) NOT NULL UNIQUE,
  display_name VARCHAR(100),
  avatar_url   VARCHAR(500),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receiver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content     TEXT NOT NULL,
  sender_hash VARCHAR(64),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_hidden   BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS idx_messages_receiver ON messages(receiver_id);

CREATE TABLE IF NOT EXISTS replies (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id BIGINT NOT NULL UNIQUE REFERENCES messages(id) ON DELETE CASCADE,
  content    TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS php_sessions (
  id         VARCHAR(128) PRIMARY KEY,
  data       TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_php_sessions_updated_at ON php_sessions (updated_at);

ALTER TABLE users        ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages     ENABLE ROW LEVEL SECURITY;
ALTER TABLE replies      ENABLE ROW LEVEL SECURITY;
ALTER TABLE php_sessions ENABLE ROW LEVEL SECURITY;